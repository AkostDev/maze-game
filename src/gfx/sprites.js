// Разворачивает описание спрайта в полные строки SPRITE×SPRITE; frame: 'a' — основной кадр, 'b' — с заменой alt
export function expand(def, frame) {
  let rows = def.rows.slice();
  if (frame === 'b' && def.alt) for (const k in def.alt) rows[k] = def.alt[k];
  if (def.m) rows = rows.map(r => r + r.split('').reverse().join(''));
  if (def.m === 2) rows = rows.concat(rows.slice().reverse());
  return rows;
}

// Проверка данных: размеры и символы палитры. Возвращает список ошибок (используется тестом и при сборке атласа).
export function validate() {
  const errs = [];
  const rowsOk = (name, rows, w, h, chars) => {
    if (rows.length !== h) errs.push(name + ': строк ' + rows.length + ', нужно ' + h);
    rows.forEach((r, y) => {
      if (r.length !== w) errs.push(name + ' строка ' + y + ': ширина ' + r.length + ', нужно ' + w);
      for (const ch of r) if (!chars(ch)) errs.push(name + ' строка ' + y + ': неизвестный символ «' + ch + '»');
    });
  };
  const inPalette = ch => ch === '.' || ch in PALETTE;
  for (const name in SPRITES) {
    rowsOk(name, expand(SPRITES[name], 'a'), SPRITE, SPRITE, inPalette);
    if (SPRITES[name].alt) rowsOk(name + '_b', expand(SPRITES[name], 'b'), SPRITE, SPRITE, inPalette);
  }
  rowsOk('GATE', GATE, 8, 16, inPalette);
  for (const name in ICONS) rowsOk('icon ' + name, ICONS[name], ICON, ICON, ch => ch === '.' || ch === '#');
  return errs;
}
